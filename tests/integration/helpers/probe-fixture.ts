function config(extras: {
  readonly gates: readonly { readonly id: string; readonly passes: boolean }[];
  readonly port: number;
  readonly service: boolean;
  readonly fakePlanAuthor: boolean;
}): string {
  const lines = ['version: 1', '', 'project:', '  baseBranch: master', ''];

  if (extras.gates.length === 0) {
    lines.push('gates: []');
  } else {
    lines.push('gates:');
    for (const gate of extras.gates) {
      // argv, never a shell line (AD-3): no quoting, no operators, nothing to interpret.
      lines.push(`  - { id: ${gate.id}, run: node gates/${gate.id}.cjs }`);
    }
  }
  lines.push('');

  if (extras.service) {
    lines.push(
      'services:',
      '  backend:',
      '    run: node app/server.cjs',
      `    port: ${extras.port}`,
      '    ready:',
      `      url: http://127.0.0.1:${extras.port}/health`,
      '      timeoutSec: 30',
      '',
    );
  }

  lines.push(
    'data:',
    '  reset: node commands/reset.cjs',
    '',
    'observations:',
    '  rowcount:',
    '    run: node commands/rowcount.cjs',
    '  version:',
    '    run: node commands/version.cjs',
    '',
  );

  if (extras.fakePlanAuthor) {
    lines.push(
      'ai:',
      '  providers:',
      '    hermetic: { adapter: fake, mode: fake-provider }',
      '  roles:',
      '    plan-author: hermetic',
      '',
    );
  }

  return `${lines.join('\n')}\n`;
}

interface PlanOptions {
  readonly epic: string;
  readonly fingerprint: string;
  readonly human: boolean;
  readonly plannedNeedsHuman: boolean;
  readonly service: boolean;
}

/**
 * The compiled plan, hand-written.
 *
 * E1-01 is an http probe against `/status`; E1-02 is an observation wrapping an http POST to
 * `/rows`, so its `delta` assertion measures a real side effect; E1-03 is a shell probe.
 * A `human` criterion is carried as needs-human with reason `human-verifiability`, which is
 * the only disposition 4.2's schema permits for it.
 */
function planYaml(options: PlanOptions): string {
  const needsHuman = (id: string, reason: string, guidance: string): string =>
    `    - criterionId: ${id}\n      disposition: needs-human\n      reason: ${reason}\n      guidance: ${guidance}\n`;

  if (options.plannedNeedsHuman) {
    // Every automated criterion deferred to a person. Q38's `not-safely-automatable`.
    const deferred = ['E1-01', 'E1-02', 'E1-03']
      .map((id) => needsHuman(id, 'not-safely-automatable', 'check this by hand'))
      .join('');
    return document(options, deferred + (options.human ? human(options) : ''));
  }

  const httpStatus = options.service
    ? `    - criterionId: E1-01
      disposition: automated
      probes:
        - id: status-probe
          surface: http
          mechanics:
            serviceId: backend
            method: GET
            path: /status
          assertions:
            - description: the service answers 200
              target: { source: status }
              comparison: equals
              expected: "200"
`
    : needsHuman('E1-01', 'not-safely-automatable', 'no service is declared in this fixture');

  const observation = options.service
    ? `    - criterionId: E1-02
      disposition: automated
      probes:
        - id: create-row
          surface: http
          mechanics:
            serviceId: backend
            method: POST
            path: /rows
            body: "{}"
          assertions:
            - description: the row was created
              target: { source: status }
              comparison: equals
              expected: "201"
        - id: rows-delta
          surface: observation
          mechanics:
            commandId: rowcount
            args: []
            around: create-row
          assertions:
            - description: exactly one row was created
              target: { source: jsonPath, path: count, phase: delta }
              comparison: equals
              expected: "1"
`
    : needsHuman('E1-02', 'not-safely-automatable', 'no service is declared in this fixture');

  const shell = `    - criterionId: E1-03
      disposition: automated
      probes:
        - id: version-probe
          surface: shell
          mechanics:
            commandId: version
            args: ["--version"]
            argumentAllowlist: ["--version"]
          assertions:
            - description: the command exits zero
              target: { source: exitCode }
              comparison: equals
              expected: "0"
            - description: it prints its version
              target: { source: stdout }
              comparison: contains
              expected: specwitness-fixture
`;

  return document(options, httpStatus + observation + shell + (options.human ? human(options) : ''));
}

function human(options: PlanOptions): string {
  return options.human
    ? `    - criterionId: E1-04
      disposition: needs-human
      reason: human-verifiability
      guidance: read the failure message aloud to somebody who did not write the code
`
    : '';
}

