/**
 * Inline fixtures for the story 4.7 end-to-end suites — a project with services, data
 * commands, observation commands, shell commands and a compiled plan.
 *
 * **These are NOT Golden Verification Corpus fixtures.** `fixtures/corpus/` is Epic 6 and
 * does not exist; AC1's and AC2's references to "Golden Corpus fixture 11" are forward
 * references. Everything here is built by the test that uses it, in a per-test temp
 * directory, and torn down afterwards — so a passing suite must not be read as corpus
 * coverage.
 *
 * The rules `verify-fixture.ts` established, kept verbatim because they still hold:
 *
 *  1. **Never this repository.** It has live linked worktrees from the agent harness, so a
 *     worktree assertion here would assert on a peer's state.
 *  2. **Never the network, never a real provider CLI, never a credential store.** Every
 *     service, gate, data command, observation and shell probe is a Node script this module
 *     writes; the only other things spawned are `git` and the built `specwitness` binary.
 *     The only sockets are on `127.0.0.1`, on a port bound and released moments earlier.
 *  3. **Per-test temp directories and ephemeral ports** (harness defect H-8: `pnpm test`
 *     runs in this worktree concurrently with the agent).
 *
 * The project is scaffolded by the SHIPPED `specwitness init` and its contract frozen by the
 * SHIPPED `specwitness contract <epic> --freeze`, so the layout and the fingerprint are the
 * product's own rather than ones a test hand-rolled and could get right for the wrong
 * reason. The PLAN is hand-written here, deliberately: a plan generated by the code under
 * test would prove only that the code agrees with itself (AD-12's rule for corpus
 * expectations, applied for the same reason).
 */

