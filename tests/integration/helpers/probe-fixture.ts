/**
 * A `plan-author` script for the shipped `fake` provider, so the AC3 auto-compilation path
 * runs with no agent CLI installed and no network.
 *
 * **This is the ONLY way that path is exercised anywhere.** A real `claude`/`codex`
 * invocation against a live subscription is the owner's dogfooding step and has never run;
 * the provenance a real CLI reports is unverified. Said here as well as in the PR body, so
 * a reader of a green suite does not conclude otherwise.
 */
function fakePlanDraft(human: boolean): string {
  const draft = {
    data: { bindings: [] },
    criteria: [
      {
        criterionId: 'E1-01',
        disposition: 'automated',
        probes: [
          {
            id: 'status-probe',
            surface: 'http',
            mechanics: { serviceId: 'backend', method: 'GET', path: '/status' },
            assertions: [
              {
                description: 'the service answers 200',
                target: { source: 'status' },
                comparison: 'equals',
                expected: '200',
              },
            ],
          },
        ],
      },
      {
        criterionId: 'E1-02',
        disposition: 'needs-human',
        reason: 'not-safely-automatable',
        guidance: 'counting rows safely needs a fixture database',
      },
      {
        criterionId: 'E1-03',
        disposition: 'automated',
        probes: [
          {
            id: 'version-probe',
            surface: 'shell',
            mechanics: {
              commandId: 'version',
              args: ['--version'],
              argumentAllowlist: ['--version'],
            },
            assertions: [
              {
                description: 'the command exits zero',
                target: { source: 'exitCode' },
                comparison: 'equals',
                expected: '0',
              },
            ],
          },
        ],
      },
      ...(human
        ? [
            {
              criterionId: 'E1-04',
              disposition: 'needs-human',
              reason: 'human-verifiability',
              guidance: 'read it aloud to somebody who did not write the code',
            },
          ]
        : []),
    ],
  };

  return JSON.stringify([JSON.stringify(draft)], null, 2);
}

/** Reads the frozen contract's fingerprint, so the plan records the product's own hash. */
async function frozenFingerprint(contractPath: string): Promise<string> {
  const text = await readFile(contractPath, 'utf8');
  const match = /^\s*fingerprint:\s*(\S+)\s*$/m.exec(text);
  if (match?.[1] === undefined || match[1] === 'null') {
    throw new Error('fixture: the frozen contract carries no fingerprint');
  }
  return match[1];
}

/**
 * Builds a project: a real git repository, the shipped `.specwitness/` layout, a fixture
 * service, deterministic commands, a frozen contract and (by default) a compiled plan.
 *
 * Leaves the working tree CLEAN, so `git status --porcelain` is the empty string before a
 * run and any change `verify` makes is visible as a diff rather than as noise (AD-8, FR-19).
 */
export async function buildProbeFixture(
  options: ProbeFixtureOptions = {},
): Promise<ProbeFixture> {
  const epic = options.epic ?? 'epic-1';
  const gates = options.gates ?? [];
  const statusCode = options.statusCode ?? 200;
  const human = options.human ?? false;
  const seedSecret = options.seedSecret ?? false;
  const service = options.service ?? true;
  const plannedNeedsHuman = options.plannedNeedsHuman ?? false;
  const writePlan = options.plan ?? true;
  const fakePlanAuthor = options.fakePlanAuthor ?? false;

  const port = await freePort();
  const root = await mkdtemp(join(tmpdir(), 'specwitness-probe-fixture-'));
  const cleanup = async (): Promise<void> => {
    await rm(root, { recursive: true, force: true });
  };

  try {
    await git(root, 'init', '--quiet');
    // `git init -b` needs git 2.28; `symbolic-ref` works back to the 2.17 floor.
    await git(root, 'symbolic-ref', 'HEAD', 'refs/heads/master');
    await writeFile(join(root, 'README.md'), '# fixture project\n', 'utf8');
    await git(root, 'add', '-A');
    await git(root, 'commit', '--quiet', '-m', 'chore: fixture base commit');

    await mkdir(join(root, 'app'), { recursive: true });
    await mkdir(join(root, 'commands'), { recursive: true });
    await writeFile(
      join(root, 'app', 'server.cjs'),
      serviceScript(port, statusCode, seedSecret),
      'utf8',
    );
    await writeFile(join(root, 'app', 'counter.txt'), '0', 'utf8');
    await writeFile(
      join(root, 'commands', 'rowcount.cjs'),
      observationScript(options.brokenObservation ?? false, seedSecret),
      'utf8',
    );
    await writeFile(join(root, 'commands', 'version.cjs'), shellScript(seedSecret), 'utf8');
    await writeFile(join(root, 'commands', 'reset.cjs'), dataScript(seedSecret), 'utf8');

    if (gates.length > 0) {
      await mkdir(join(root, 'gates'), { recursive: true });
      for (const gate of gates) {
        const path = join(root, 'gates', `${gate.id}.cjs`);
        await writeFile(path, gateScript(gate.passes, seedSecret), 'utf8');
        await chmod(path, 0o644);
      }
    }

    // The shipped scaffolder, so the fixture uses the real layout (Q11's nested
    // `.specwitness/.gitignore`) rather than one invented here.
    const init = await runCli(['init'], { cwd: root });
    if (init.exitCode !== 0) {
      throw new Error(`fixture: 'specwitness init' failed (${init.exitCode}): ${init.stderr}`);
    }

    await writeFile(
      join(root, '.specwitness', 'config.yaml'),
      config({ gates, port, service, fakePlanAuthor }),
      'utf8',
    );

    if (fakePlanAuthor) {
      await mkdir(join(root, 'fake-provider'), { recursive: true });
      await writeFile(
        join(root, 'fake-provider', 'plan-author.json'),
        fakePlanDraft(human),
        'utf8',
      );
    }

    const contractPath = join(root, '.specwitness', 'contracts', `${epic}.yaml`);
    await writeFile(contractPath, draftContract(epic, human, options.humanOnly ?? false), 'utf8');

    // The SHIPPED freeze, so the fingerprint is the product's own.
    const frozen = await runCli(['contract', epic, '--freeze'], { cwd: root });
    if (frozen.exitCode !== 0) {
      throw new Error(
        `fixture: 'specwitness contract ${epic} --freeze' failed (${frozen.exitCode}): ${frozen.stderr}`,
      );
    }

    if (writePlan) {
      await mkdir(join(root, '.specwitness', 'plans'), { recursive: true });
      await writeFile(
        join(root, '.specwitness', 'plans', `${epic}.yaml`),
        planYaml({
          epic,
          fingerprint: await frozenFingerprint(contractPath),
          human,
          plannedNeedsHuman,
          service,
        }),
        'utf8',
      );
    }

    await git(root, 'add', '-A');
    await git(root, 'commit', '--quiet', '-m', 'chore: fixture project');

    return {
      root,
      epic,
      port,
      status: async () => await git(root, 'status', '--porcelain'),
      cleanup,
    };
  } catch (error) {
    await cleanup();
    throw error;
  }
}
