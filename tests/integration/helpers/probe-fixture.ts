/**
 * A distinctive string seeded into every capture path, so the seeded-secret proof has
 * something unmistakable to look for.
 *
 * DELIBERATELY NOT SHAPED LIKE A REAL VENDOR KEY: the repository's pre-commit secret
 * scanner rejects `sk-…` literals on sight, correctly, and the shape is irrelevant to what
 * is proved — `redactText` fires on the ASSIGNMENT NAME (`AWS_SECRET_ACCESS_KEY=`,
 * `Authorization:`), never on the value's format.
 */
export const SECRET = 'zzTOPSECRETzz-4f2a9c1b';

/** The assignment forms each capture path emits the secret in. */
export const SECRET_ASSIGNMENT = `AWS_SECRET_ACCESS_KEY=${SECRET}`;

export interface ProbeFixtureOptions {
  /** Canonical epic id. Default `epic-1`. */
  readonly epic?: string;
  /** Declare gates. Default: none — this epic's fixtures verify through probes. */
  readonly gates?: readonly { readonly id: string; readonly passes: boolean }[];
  /** The status code the fixture service answers `/status` with. Default 200. */
  readonly statusCode?: number;
  /** Include a `verifiability: human` criterion (and plan it as needs-human). Default false. */
  readonly human?: boolean;
  /**
   * A contract whose criteria are ALL `verifiability: human`.
   *
   * Nothing mechanical can ever adjudicate such a contract, and 4.2's schema requires every
   * one of its criteria to be carried as needs-human — so with no gates declared this is a
   * project that is unverifiable no matter what a plan-author produces, which is knowable
   * before a provider is invoked.
   */
  readonly humanOnly?: boolean;
  /**
   * Plan the automated criteria as `needs-human` with reason `not-safely-automatable`,
   * rather than mapping them to probes. Default false.
   */
  readonly plannedNeedsHuman?: boolean;
  /** Write the compiled plan. Default true; `false` exercises the AC3 cells. */
  readonly plan?: boolean;
  /** Seed `SECRET` into every capture path. Default false. */
  readonly seedSecret?: boolean;
  /** Make the observation command emit non-JSON, so the criterion errors. Default false. */
  readonly brokenObservation?: boolean;
  /** Configure the shipped `fake` provider for the `plan-author` role. Default false. */
  readonly fakePlanAuthor?: boolean;
  /** Declare the service, and probe it. Default true. */
  readonly service?: boolean;
}

export interface ProbeFixture {
  readonly root: string;
  readonly epic: string;
  readonly port: number;
  /** `git status --porcelain`, for the AD-8 "source repo untouched" assertions. */
  status(): Promise<string>;
  cleanup(): Promise<void>;
}

/**
 * A port nothing is listening on, right now.
 *
 * Bound and released rather than picked from a range: two concurrent vitest workers in this
 * worktree would otherwise collide, which is harness defect H-8 exactly. The window between
 * release and the service binding it is a genuine race and is accepted — the alternative is
 * a fixed port, which races with certainty rather than occasionally.
 */
export async function freePort(): Promise<number> {
  return await new Promise<number>((resolvePort, rejectPort) => {
    const server = createServer();
    server.once('error', rejectPort);
    server.listen(0, '127.0.0.1', () => {
      const address = server.address();
      if (address === null || typeof address === 'string') {
        server.close(() => rejectPort(new Error('fixture: could not allocate a port')));
        return;
      }
      const { port } = address;
      server.close(() => resolvePort(port));
    });
  });
}

async function git(cwd: string, ...args: string[]): Promise<string> {
  const result = await execa('git', args, {
    cwd,
    // A hermetic identity and no user config: the fixture must not depend on whatever the
    // machine running the suite happens to have configured.
    env: {
      GIT_AUTHOR_NAME: 'SpecWitness Fixture',
      GIT_AUTHOR_EMAIL: 'fixture@example.invalid',
      GIT_COMMITTER_NAME: 'SpecWitness Fixture',
      GIT_COMMITTER_EMAIL: 'fixture@example.invalid',
      GIT_CONFIG_GLOBAL: '/dev/null',
      GIT_CONFIG_SYSTEM: '/dev/null',
    },
    extendEnv: true,
  });
  return result.stdout;
}

/**
 * The fixture application: an HTTP service with a health endpoint, a status endpoint whose
 * code the fixture chooses, and a counter it increments on POST.
 *
 * Deterministic by construction. The counter lives in a file under the SERVICE's own
 * directory inside the worktree, so an observation command can read it — which is what makes
 * a before/after `delta` assertion meaningful rather than a comparison of two zeros.
 */
function serviceScript(port: number, statusCode: number, seedSecret: boolean): string {
  return `const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const counter = path.join(__dirname, 'counter.txt');

function read() {
  try { return Number(fs.readFileSync(counter, 'utf8').trim()) || 0; } catch { return 0; }
}

// Seeded into a RESPONSE HEADER and the BODY, both of which the http executor captures.
const secret = ${JSON.stringify(seedSecret ? SECRET_ASSIGNMENT : '')};

const server = http.createServer((request, response) => {
  const headers = { 'content-type': 'application/json' };
  if (secret !== '') {
    headers['x-debug-credentials'] = 'Authorization: Bearer ' + ${JSON.stringify(SECRET)};
  }
  if (request.url === '/health') {
    response.writeHead(200, headers);
    response.end(JSON.stringify({ status: 'ok', note: secret }));
    return;
  }
  if (request.url === '/status') {
    response.writeHead(${statusCode}, headers);
    response.end(JSON.stringify({ status: ${statusCode}, note: secret }));
    return;
  }
  if (request.url === '/rows') {
    fs.writeFileSync(counter, String(read() + 1));
    response.writeHead(201, headers);
    response.end(JSON.stringify({ created: true, note: secret }));
    return;
  }
  response.writeHead(404, headers);
  response.end('{}');
});

// Never exits on its own: a service is torn down by its process group.
server.listen(${port}, '127.0.0.1', () => {
  process.stdout.write('listening on ${port}\\n');
  if (secret !== '') { process.stdout.write('service env: ' + secret + '\\n'); }
});
`;
}

/** Prints the counter as JSON on stdout and exits 0 — the observation contract (Q35). */
function observationScript(broken: boolean, seedSecret: boolean): string {
  if (broken) {
    // A command that emits NON-JSON is criterion `error` (infra), never a product fail.
    return "process.stdout.write('not json at all\\n');\nprocess.exit(0);\n";
  }
  return `const fs = require('node:fs');
const path = require('node:path');
const counter = path.join(__dirname, '..', 'app', 'counter.txt');
let value = 0;
try { value = Number(fs.readFileSync(counter, 'utf8').trim()) || 0; } catch {}
${seedSecret ? `process.stderr.write('observation env: ${SECRET_ASSIGNMENT}\\n');\n` : ''}process.stdout.write(JSON.stringify({ count: value }) + '\\n');
process.exit(0);
`;
}

/** Echoes its own argv and exits 0 — the AD-3 no-shell witness, plus a shell assertion. */
function shellScript(seedSecret: boolean): string {
  return `${seedSecret ? `process.stderr.write('shell env: ${SECRET_ASSIGNMENT}\\n');\n` : ''}process.stdout.write('specwitness-fixture 1.0.0\\n');
process.stdout.write(JSON.stringify(process.argv.slice(2)) + '\\n');
process.exit(0);
`;
}

/** Resets the counter — the data command (4.3), which produces no verdict. */
function dataScript(seedSecret: boolean): string {
  return `const fs = require('node:fs');
const path = require('node:path');
fs.mkdirSync(path.join(__dirname, '..', 'app'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'app', 'counter.txt'), '0');
${seedSecret ? `process.stdout.write('data env: ${SECRET_ASSIGNMENT}\\n');\n` : ''}process.stdout.write('reset ok\\n');
process.exit(0);
`;
}

function gateScript(passes: boolean, seedSecret: boolean): string {
  const secret = seedSecret ? `process.stdout.write('gate env: ${SECRET_ASSIGNMENT}\\n');\n` : '';
  return passes
    ? `${secret}process.stdout.write('gate ok\\n');\nprocess.exit(0);\n`
    : `${secret}process.stdout.write('GATE-FAILED-MARKER\\n');\nprocess.exit(1);\n`;
}

